class TokenConfig {
  final String address;
  final String symbol;
  final String name;
  final int decimals;
  final String logoUrl;
  final String networkId;

  TokenConfig({
    required this.address,
    required this.symbol,
    required this.name,
    required this.decimals,
    required this.logoUrl,
    required this.networkId,
  });
}
